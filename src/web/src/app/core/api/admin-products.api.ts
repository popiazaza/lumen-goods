import { HttpClient } from '@angular/common/http';
import { Service, inject } from '@angular/core';
import { Observable } from 'rxjs';
import { API_BASE_URL } from './api-base-url';
import { PagedResult, toQueryParams } from './paged-result';
import { ProductAvailability, ProductCategory } from './products.api';

// Contract: Lumen.Api/Admin/AdminProductContracts.cs (admin role; 401 signed out, 403 without it).

export interface AdminProductImage {
  /**
  File name in the own-media library: what create and update send.
  */
  file: string;
  url: string;
  isPrimary: boolean;
}

/**
One of Lumen Goods' own products, with stock and the concurrency version.
*/
export interface AdminProduct {
  id: string;
  sku: string;
  name: string;
  description: string;
  category: ProductCategory;
  /**
  USD with two decimals.
  */
  price: number | null;
  images: AdminProductImage[];
  attributes: Record<string, string>;
  onHand: number;
  /**
  Units held by orders awaiting payment; on hand can never go below this (BR-ADM-01).
  */
  reserved: number;
  availability: ProductAvailability;
  isActive: boolean;
  sellable: boolean;
  createdUtc: string;
  lastUpdatedUtc: string;
  /**
  Opaque: sent back unchanged with an update. A stale one gets 409.
  */
  version: string;
}

/**
An image products can use.
*/
export interface OwnMediaFile {
  file: string;
  url: string;
}

/**
The editable fields shared by create and update.
*/
export interface OwnProductInput {
  name: string;
  description: string;
  category: ProductCategory;
  price: number;
  attributes: Record<string, string>;
  /**
  Own-media file names in display order; the first is the primary image.
  */
  images: string[];
  onHand: number;
}

export interface CreateOwnProduct extends OwnProductInput {
  /**
  Generated by the API when left out.
  */
  sku: string | null;
}

export interface UpdateOwnProduct extends OwnProductInput {
  version: string;
}

export type ProductStatusFilter = 'all' | 'active' | 'inactive';

export interface AdminProductFilter {
  q?: string;
  status?: ProductStatusFilter;
  category?: ProductCategory | null;
  page?: number;
  pageSize?: number;
}

/**
`/api/v1/admin/products` and `/api/v1/admin/own-media`.
*/
@Service()
export class AdminProductsApi {
  private readonly http = inject(HttpClient);
  private readonly baseUrl = inject(API_BASE_URL);

  /**
  Sorted by name.
  */
  list(filter: AdminProductFilter): Observable<PagedResult<AdminProduct>> {
    return this.http.get<PagedResult<AdminProduct>>(`${this.baseUrl}/admin/products`, {
      params: toQueryParams({
        q: filter.q,
        status: filter.status === 'all' ? null : filter.status,
        category: filter.category,
        page: filter.page,
        pageSize: filter.pageSize,
      }),
    });
  }

  /**
  404 for an unknown id.
  */
  get(id: string): Observable<AdminProduct> {
    return this.http.get<AdminProduct>(this.productUrl(id));
  }

  /**
  400 with errors keyed by field; 409 when the SKU is taken.
  */
  create(product: CreateOwnProduct): Observable<AdminProduct> {
    return this.http.post<AdminProduct>(`${this.baseUrl}/admin/products`, product);
  }

  /**
  409 when `version` is stale or on hand would go below reserved (BR-ADM-01).
  */
  update(id: string, product: UpdateOwnProduct): Observable<AdminProduct> {
    return this.http.put<AdminProduct>(this.productUrl(id), product);
  }

  /**
  Hides the product from the shop; never deletes it (orders reference it). Idempotent.
  */
  deactivate(id: string): Observable<AdminProduct> {
    return this.http.post<AdminProduct>(`${this.productUrl(id)}/deactivate`, null);
  }

  reactivate(id: string): Observable<AdminProduct> {
    return this.http.post<AdminProduct>(`${this.productUrl(id)}/reactivate`, null);
  }

  /**
  The image library own products pick from.
  */
  media(): Observable<OwnMediaFile[]> {
    return this.http.get<OwnMediaFile[]>(`${this.baseUrl}/admin/own-media`);
  }

  private productUrl(id: string): string {
    return `${this.baseUrl}/admin/products/${encodeURIComponent(id)}`;
  }
}
